export function getAffirmationForDate(dateStr: string): Affirmation {
  // Compute day index deterministically
  const d = new Date(dateStr + 'T00:00:00');
  const startOfYear = new Date(d.getFullYear(), 0, 1);
  const diff = d.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay) + 1;

  const index = Math.abs((d.getFullYear() * 31 + d.getMonth() * 17 + d.getDate())) % AFFIRMATIONS_DB.length;
  const base = AFFIRMATIONS_DB[index];

  return {
    ...base,
    dayOfYear
  };
}
